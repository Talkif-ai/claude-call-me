// Mirrors test-vectors/*.json into tests/vectors.ts: the plugin's test runner
// loads only code files, so the tests read the shared vectors from there, byte
// for byte (each file's exact text as a string). `--check` fails when the
// mirror is stale instead of writing it.
//
//   node scripts/sync-vectors.mjs [--check]
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'

const root = new URL('..', import.meta.url).pathname
const files = readdirSync(`${root}test-vectors`).filter(f => f.endsWith('.json')).sort()
const body = files.map(f => `  ${JSON.stringify(f)}: ${JSON.stringify(readFileSync(`${root}test-vectors/${f}`, 'utf8'))},`).join('\n')
const text = `// Generated by scripts/sync-vectors.mjs from test-vectors/*.json. Do not edit.\nexport const VECTOR_FILES: Record<string, string> = {\n${body}\n}\n`
const out = `${root}tests/vectors.ts`
if (process.argv.includes('--check')) {
  if (readFileSync(out, 'utf8') !== text) {
    console.error('tests/vectors.ts is stale: run node scripts/sync-vectors.mjs')
    process.exit(1)
  }
} else writeFileSync(out, text)
