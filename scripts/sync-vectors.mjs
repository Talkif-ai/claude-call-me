// Mirrors the shared test-vectors/ (copied byte for byte from talkif-agents) into code
// files, because the plugin's runtime and test runner load only code:
//   tests/vectors.ts         every file's exact text, for the tests (SHA256SUMS included)
//   hooks/shared-tables.ts   tiers.json and secrets.json, which the hooks classify and scrub by
// `--check` fails when a mirror is stale instead of writing it.
//
//   node scripts/sync-vectors.mjs [--check]
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'

const root = new URL('..', import.meta.url).pathname
const read = f => readFileSync(`${root}test-vectors/${f}`, 'utf8')
const files = readdirSync(`${root}test-vectors`).filter(f => f.endsWith('.json') || f === 'SHA256SUMS').sort()
const body = files.map(f => `  ${JSON.stringify(f)}: ${JSON.stringify(read(f))},`).join('\n')
const outputs = {
  'tests/vectors.ts': `// Generated by scripts/sync-vectors.mjs from test-vectors/. Do not edit.\nexport const VECTOR_FILES: Record<string, string> = {\n${body}\n}\n`,
  'hooks/shared-tables.ts':
    `// Generated by scripts/sync-vectors.mjs from test-vectors/tiers.json and secrets.json. Do not edit.\n` +
    `// The exact text of the shared tables; tests/vectors.ts holds the same bytes and SHA256SUMS.\n` +
    `export const TIERS_JSON: string = ${JSON.stringify(read('tiers.json'))}\n` +
    `export const SECRETS_JSON: string = ${JSON.stringify(read('secrets.json'))}\n`,
}
let stale = false
for (const [out, text] of Object.entries(outputs)) {
  if (!process.argv.includes('--check')) writeFileSync(`${root}${out}`, text)
  else if (readFileSync(`${root}${out}`, 'utf8') !== text) {
    console.error(`${out} is stale: run node scripts/sync-vectors.mjs`)
    stale = true
  }
}
if (stale) process.exit(1)
